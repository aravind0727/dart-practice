void main() {
  int num1 = 20;
  int num2 = 6;

  print("===== Calculator Program =====");
  print("Number 1 = $num1");
  print("Number 2 = $num2");

  print("Sum = ${num1 + num2}");
  print("Difference = ${num1 - num2}");
  print("Product = ${num1 * num2}");
  print("Quotient = ${num1 / num2}");
  print("Integer Quotient = ${num1 ~/ num2}");
  print("Remainder = ${num1 % num2}");
}
